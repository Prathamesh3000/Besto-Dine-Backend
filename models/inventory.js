const mongoose = require('mongoose');

// ─── Stock Adjustment History ────────────────────────────────────────────────
const stockAdjustmentSchema = new mongoose.Schema({
    type: {
        type: String,
        enum: ['restock', 'usage', 'waste', 'correction', 'return'],
        required: true
    },
    quantity: { type: Number, required: true },
    previousStock: { type: Number, required: true },
    newStock: { type: Number, required: true },
    reason: { type: String, default: '' },
    adjustedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    date: { type: Date, default: Date.now }
});

// ─── Main Inventory Schema ───────────────────────────────────────────────────
const inventorySchema = new mongoose.Schema({
    // Tenant link — added by Phase 1 SaaS migration. Required for all
    // tenant-scoped reads/writes after the backfill has run. The Default
    // Restaurant created by seedDefaultTenant.js owns all pre-migration data.
    restaurant: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Restaurant',
        required: true,
        index: true,
    },
    // Phase 6 — optional branch link. null = tenant-level (shared
    // across all branches). When set, this item belongs to a specific
    // branch's stock pool.
    branch: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Branch',
        default: null,
        index: true,
    },
    itemId: {
        type: String,
        required: true,
        // NOT globally unique. itemId is a per-tenant human-readable
        // serial (INV-001, INV-002, …) generated by generateNextId()
        // which already filters by `restaurant`. A global unique
        // constraint here caused E11000 collisions whenever Tenant B
        // tried to create its first item after Tenant A already had
        // INV-001 — bulk imports for fresh tenants failed wholesale.
        // The compound `{ restaurant: 1, itemId: 1 }` index below
        // enforces tenant-scoped uniqueness instead.
    },
    name: {
        type: String,
        required: [true, 'Please provide item name'],
        trim: true
    },
    category: {
        type: String,
        required: [true, 'Please select a category'],
        enum: [
            'Raw Ingredients',
            'Beverages',
            'Dairy & Eggs',
            'Spices & Seasonings',
            'Packaging',
            'Cleaning Supplies',
            'Kitchen Equipment',
            'Bakery Items',
            'Fruits & Vegetables',
            'Frozen Goods',
            'Oils & Sauces',
            'Other'
        ],
        index: true
    },
    unit: {
        type: String,
        required: [true, 'Please select a unit'],
        enum: ['kg', 'g', 'L', 'mL', 'pcs', 'dozen', 'box', 'pack', 'bottle', 'can']
    },
    currentStock: {
        type: Number,
        required: true,
        default: 0,
        min: 0
    },
    minStock: {
        type: Number,
        required: [true, 'Please set minimum stock level'],
        min: 0
    },
    maxStock: {
        type: Number,
        min: 0,
        default: 0  // 0 means no max limit
    },
    costPerUnit: {
        type: Number,
        required: [true, 'Please provide cost per unit'],
        min: 0
    },
    supplier: {
        name: { type: String, default: '' },
        contact: { type: String, default: '' }
    },
    lastRestocked: { type: Date },
    expiryDate: { type: Date },
    // Spec 10.3.1 — perishability metadata. `expiryTracking` is the
    // master Yes/No flag (off = non-perishable item, expiry/shelf-life
    // inputs are hidden in the UI). `shelfLifeDays` is the typical
    // usable life from restock; 0 = not specified.
    expiryTracking: { type: Boolean, default: false },
    shelfLifeDays: { type: Number, min: 0, default: 0 },
    status: {
        type: String,
        enum: ['in-stock', 'low-stock', 'out-of-stock'],
        default: 'in-stock',
        index: true
    },
    adjustmentHistory: [stockAdjustmentSchema]
}, { timestamps: true });

// ─── Auto-calculate status before save ───────────────────────────────────────
inventorySchema.pre('save', function () {
    if (this.currentStock <= 0) {
        this.status = 'out-of-stock';
    } else if (this.currentStock <= this.minStock) {
        this.status = 'low-stock';
    } else {
        this.status = 'in-stock';
    }
});

// ─── Performance indexes ─────────────────────────────────────────────────────
// Tenant-scoped uniqueness on the human-readable itemId. Replaces the
// old global `unique: true` on `itemId` which broke bulk imports for
// fresh tenants (E11000 INV-001 collision with another tenant's first
// item). Drop the legacy index manually on existing environments:
//   db.inventories.dropIndex('itemId_1')
inventorySchema.index({ restaurant: 1, itemId: 1 }, { unique: true });
inventorySchema.index({ category: 1, status: 1 });
inventorySchema.index({ name: 'text' });
inventorySchema.index({ currentStock: 1, minStock: 1 });

// ─── Virtual: stock value ────────────────────────────────────────────────────
inventorySchema.virtual('stockValue').get(function () {
    return this.currentStock * this.costPerUnit;
});

inventorySchema.set('toJSON', { virtuals: true });
inventorySchema.set('toObject', { virtuals: true });

// BUGS_REPORT #30 — auto-scope queries to the request tenant (utils/tenantScopePlugin.js).
inventorySchema.plugin(require('../utils/tenantScopePlugin'));

module.exports = mongoose.model('Inventory', inventorySchema);
